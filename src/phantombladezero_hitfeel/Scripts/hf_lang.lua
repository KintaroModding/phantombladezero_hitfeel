-- The text of `s` in the current language. Chinese is the source; a key missing from a table falls back to it.
function Lang.t(s)
  if s == nil or s == "" or Lang.code == "zh" then return s end
  local tbl = T[Lang.code]
  local v = tbl and tbl[s]
  if v == nil then
    Lang.missing[Lang.code .. ": " .. s] = true
    return s
  end
  return v
end

function Lang.f(s, ...) return string.format(Lang.t(s), ...) end

function Lang.known(code)
  for _, l in ipairs(Lang.LIST) do
    if l.code == code then return true end
  end
  return false
end

function Lang.name(code)
  code = code or Lang.code
  for _, l in ipairs(Lang.LIST) do
    if l.code == code then return l.name end
  end
  return tostring(code)
end

-- A game culture ("zh-Hans", "zh-Hant-TW", "ja-JP", "ko", "en-US", ...) to one of the four; anything else is English.
function Lang.fromCulture(c)
  c = tostring(c or ""):lower()
  for _, code in ipairs({ "zh", "ja", "ko" }) do
    if c == code or c:sub(1, #code + 1) == code .. "-" or c:sub(1, #code + 1) == code .. "_" then return code end
  end
  return "en"
end

-- How wide a text runs, in units of half a CJK character at the same size: a CJK, kana or Hangul character is 2,
-- Latin letters about 0.5 (i, l, spaces) to 1.7 (m, w), so a line can be cut to fit its place in any language.
local NARROW, SEMI, WIDE = "[ iljI%.,:;'|!%(%)%[%]]", "[ftrJ%-/]", "[mwMW]"
function Lang.charWidth(ch)
  if #ch == 1 then
    if ch:find(NARROW) then return 0.5 end
    if ch:find(SEMI) then return 0.75 end
    if ch:find(WIDE) then return 1.7 end
    if ch:find("%u") then return 1.3 end
    return 1.05
  end
  if ch == "·" then return 0.5 end
  return #ch == 2 and 1.05 or 2
end

function Lang.width(s)
  local w = 0
  for ch in tostring(s or ""):gmatch("[%z\1-\127\194-\244][\128-\191]*") do w = w + Lang.charWidth(ch) end
  return w
end

return Lang
